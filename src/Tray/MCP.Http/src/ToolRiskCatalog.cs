    /// <summary>Every tool name in the catalog, safe and dangerous.</summary>
    public static IEnumerable<string> AllNames => DangerousTools.Concat(SafeTools);

    /// <summary>True when the tool is listed, as safe or as dangerous.</summary>
    public static bool IsClassified(string? toolName) =>
        toolName is not null && (DangerousTools.Contains(toolName) || SafeTools.Contains(toolName));

    /// <summary>Safe only for a tool listed as safe; dangerous for a dangerous, unknown, null or empty name.</summary>
    public static ToolRisk Classify(string? toolName) =>
        toolName is not null && SafeTools.Contains(toolName) ? ToolRisk.Safe : ToolRisk.Dangerous;
