/// <summary>How much a tool can hurt when a client that was steered by hostile text (a log line, a build message) calls it.</summary>
public enum ToolRisk
{
    /// <summary>Runs without asking.</summary>
    Safe,

    /// <summary>Needs the user's confirmation in the tray for each call.</summary>
    Dangerous,
}

